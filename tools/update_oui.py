"""Regenerate src/oui_data.py from the official IEEE MA-L registry.

Usage (from the project root):
    python tools/update_oui.py              # download from IEEE
    python tools/update_oui.py oui.csv      # use a local copy of the CSV

Only the 24-bit prefix and the organization name are kept (no addresses).
Source: https://standards-oui.ieee.org/oui/oui.csv
"""
import csv
import io
import sys
import urllib.request
from datetime import date
from pathlib import Path

URL = "https://standards-oui.ieee.org/oui/oui.csv"
OUT = Path(__file__).resolve().parent.parent / "src" / "oui_data.py"


def load(arg):
    if arg:
        return Path(arg).read_text(encoding="utf-8-sig")
    req = urllib.request.Request(URL, headers={"User-Agent": "toolDHCP-oui-update"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8-sig")


def main():
    text = load(sys.argv[1] if len(sys.argv) > 1 else None)
    rows = {}
    for r in csv.DictReader(io.StringIO(text)):
        if r["Registry"] != "MA-L":
            continue
        a = r["Assignment"].upper()
        rows[f"{a[0:2]}:{a[2:4]}:{a[4:6]}"] = " ".join(r["Organization Name"].split())
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        f.write('"""AUTO-GENERATED by tools/update_oui.py - do not edit by hand.\n\n')
        f.write(f"Source: IEEE MA-L registry ({URL}), generated {date.today()}.\n")
        f.write(f'{len(rows)} entries.\n"""\nOUI = {{\n')
        for k in sorted(rows):
            f.write(f"    {k!r}: {rows[k]!r},\n")
        f.write("}\n")
    print(f"{len(rows)} entries -> {OUT}")


if __name__ == "__main__":
    main()
